/** Lines the rules may match without meaning anything to a player. */
const LINE_EXCEPTIONS: readonly RegExp[] = [
  /^\s*(\/\/|\*|\/\*|\{\/\*)/, // comments: the code may explain what it replaced
  /reserved-names/, // this lint's own name in scripts and workflows
]

const CODE_EXTENSIONS = new Set(['.ts', '.tsx', '.js', '.mjs'])
const TEXT_EXTENSIONS = new Set([...CODE_EXTENSIONS, '.json', '.liquid', '.html', '.css', '.svg', '.txt', '.xml', '.webmanifest', '.md'])
const SKIP_DIRS = new Set(['node_modules', '_generated', '.output', 'dist'])

/** Quoted strings on one line, and JSX text with its tags and expressions taken out. */
const STRING_LITERAL = /'(?:[^'\\\n]|\\.)*'|"(?:[^"\\\n]|\\.)*"|`(?:[^`\\\n]|\\.)*`/g
/** Takes the code out of copy: `${...}` in a template literal, `{...}` in JSX, innermost first so nesting works. */
function withoutExpressions(text: string): string {
  let out = text
  while (/\{[^{}]*\}/.test(out)) out = out.replace(/\$?\{[^{}]*\}/g, ' ')
  // An expression that opens on this line and closes on another, or the reverse.
  return out.replace(/\{[^}]*$/, ' ').replace(/^[^{]*\}/, ' ')
}
/** A route, a module specifier, a lowercase id such as an icon kind or a query key: code, not copy. */
const NOT_COPY = /^(\/[\w/$.?=&-]*|@?[\w./-]+\/[\w./-]+|[a-z][\w-]*)$/

/**
 * What a player could read on a line of code: its string literals, and for JSX the prose between tags. Identifiers
 * (`todo.tasks`, `api.meetings`) are code, not copy, and stay out; routes stay as they are (a path is not prose).
 */
function playerText(line: string, extension: string): string[] {
  if (!CODE_EXTENSIONS.has(extension)) return [line]
  const segments = (line.match(STRING_LITERAL) ?? [])
    .map((literal) => withoutExpressions(literal.slice(1, -1)))
    .filter((text) => !NOT_COPY.test(text))
  const trimmed = line.trim()
  // JSX prose: a line that opens a tag, or a continuation line with none of the punctuation code needs (an object
  // literal's `key: 'value'` pairs are code; their strings were taken above).
  // Test the punctuation after removing `{expression}` holes, so a prose line that interpolates a value is still read.
  const bare = withoutExpressions(trimmed)
  const moduleLine = /^(import|export)\b|^\}? ?from ['"]/.test(trimmed)
  if (extension === '.tsx' && !moduleLine && (trimmed.startsWith('<') || !/[(=;{|[\]]|\?:|\w: ['"`]/.test(bare))) {
    const prose = bare.replace(/<[^>]*>/g, ' ').trim()
    if (prose !== '') segments.push(prose)
  }
  return segments
}
function* walk(dir: string): Generator<string> {
  for (const entry of readdirSync(dir)) {
    if (SKIP_DIRS.has(entry)) continue
    const full = join(dir, entry)
    if (statSync(full).isDirectory()) yield* walk(full)
    else yield full
  }
}

const posix = (path: string) => path.split(sep).join('/')
const allowed = (rel: string) => ALLOWLIST.find((entry) => rel === entry.path || rel.startsWith(`${entry.path}/`))

interface Hit { readonly file: string; readonly line: number; readonly rule: Rule; readonly text: string }

function scanFile(rel: string, full: string): Hit[] {
  const hits: Hit[] = []
  for (const rule of RULES) if (rule.category === 'assets' && rule.pattern.test(rel)) hits.push({ file: rel, line: 0, rule, text: '(file name)' })
  const dot = rel.lastIndexOf('.')
  const extension = dot < 0 ? '' : rel.slice(dot)
  if (!TEXT_EXTENSIONS.has(extension)) return hits
  const lines = readFileSync(full, 'utf8').split('\n')
  lines.forEach((text, index) => {
    if (LINE_EXCEPTIONS.some((exception) => exception.test(text))) return
    const segments = playerText(text, extension)
    for (const rule of RULES) {
      if (rule.category === 'assets' && rule.label === 'floors/[a-z_]+\\.png') continue
      const segment = segments.find((candidate) => rule.pattern.test(candidate))
      if (segment !== undefined) hits.push({ file: rel, line: index + 1, rule, text: segment.trim().slice(0, 140) })
    }
  })
  return hits
}

function main(): number {
  const summary = process.argv.includes('--summary')
  const failures: Hit[] = []
  const hidden = new Map<string, number>()
  const used = new Set<string>()
  for (const scanRoot of SCAN_ROOTS) {
    for (const full of walk(join(root, scanRoot))) {
      const rel = posix(relative(root, full))
      const hits = scanFile(rel, full)
      if (hits.length === 0) continue
      const entry = allowed(rel)
      if (entry) {
        used.add(entry.path)
        hidden.set(entry.path, (hidden.get(entry.path) ?? 0) + hits.length)
      } else failures.push(...hits)
    }
  }
  if (summary) {
    console.log('Hits hidden by the allowlist (shrink this to the permanent entries before publishing):')
    for (const entry of ALLOWLIST) console.log(`  ${String(hidden.get(entry.path) ?? 0).padStart(5)}  ${entry.path}  (${entry.reason})`)
  }
  const stale = ALLOWLIST.filter((entry) => !used.has(entry.path))
  for (const entry of stale) console.log(`Allowlist entry no longer needed (remove it when the branch that cleaned it has merged): ${entry.path}`)
  for (const hit of failures) console.log(`${hit.file}:${hit.line}: [${hit.rule.category}] ${hit.rule.label}: ${hit.text}`)
  if (failures.length > 0) {
    console.log(`\n${failures.length} reserved name${failures.length === 1 ? '' : 's'} in player-facing source. Desk Crawler's names, art and office framing are reserved: say it Volta's way or, for files owned elsewhere, add them to ALLOWLIST in tools/lint/reserved-names.ts.`)
    return 1
  }
  console.log(`No reserved names outside the allowlist (${ALLOWLIST.length} allowlisted paths).`)
  return 0
}

process.exit(main())
